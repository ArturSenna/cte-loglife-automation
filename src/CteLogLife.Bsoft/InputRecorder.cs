using System.Runtime.InteropServices;

namespace CteLogLife.Bsoft;

public enum RecordedKind { Click, DoubleClick, RightClick, Key }

/// <summary>One thing the operator did while the bot waited: a click at a screen point or a key.</summary>
public sealed record RecordedStep(RecordedKind Kind, int X = 0, int Y = 0, int Key = 0, bool Alt = false,
    bool Shift = false, int DelayMs = 0);

/// <summary>
/// What the operator did on an unknown screen. <see cref="Unrepeatable"/> says why it must not be
/// repeated by the bot (typed text, a shortcut that changes data, too many actions); null when it can.
/// </summary>
public sealed record Recording(IReadOnlyList<RecordedStep> Steps, string? Unrepeatable = null)
{
    public static Recording Empty { get; } = new([]);
}

public interface IInputRecorder
{
    void Start();

    /// <summary>Stops watching and returns what was seen since <see cref="Start"/>.</summary>
    Recording Stop();
}

/// <summary>
/// Watches the mouse and the keyboard of the whole desktop while the bot is parked at an unknown screen.
/// It keeps clicks and the few keys that answer a dialog (Enter, Esc, Tab, Space, arrows, Alt+letter).
/// Text is never stored: typing it only marks the recording as not repeatable. Clicks and keys on this
/// program's own windows, the pause shortcuts and anything the bot itself sends are left out.
/// </summary>
public sealed class InputRecorder : IInputRecorder
{
    public const int MaxSteps = 8;

    private const int VkPause = 0x13, VkControl = 0x11, VkAlt = 0x12, VkShift = 0x10, VkLeftWin = 0x5B, VkRightWin = 0x5C;

    private readonly List<RecordedStep> _steps = [];
    private readonly HashSet<int> _held = [];
    private readonly ManualResetEventSlim _ready = new(false);
    private readonly uint _ownProcess = (uint)Environment.ProcessId;
    private readonly uint _doubleClickMs = Native.GetDoubleClickTime();
    private Thread? _thread;
    private uint _threadId;
    private Native.HookProc? _mouseProc, _keyProc; // kept alive while the hooks exist
    private string? _unrepeatable;
    private long _lastAt;

    /// <summary>Also keep input generated by programs and input on this program's windows (self-test only).</summary>
    private bool _probing;

    /// <summary>False when Windows refused the hooks: nothing will be recorded.</summary>
    public bool Installed { get; private set; }

    /// <summary>When set, only clicks and keys that go to this program count.</summary>
    public uint OnlyProcess { get; init; }

    /// <summary>
    /// Called from the hook's thread each time something is recorded (or refused as not repeatable).
    /// It must return quickly.
    /// </summary>
    public Action? Seen { get; init; }

    /// <summary>
    /// A recorder that also sees input sent by programs and input on this program's own windows, so the
    /// self-test can play the operator on a window of its own.
    /// </summary>
    public static InputRecorder ForSelfTest() => new() { _probing = true };

    /// <summary>The same, watching one program only, as the bot does during a pause.</summary>
    public static InputRecorder ForSelfTest(uint onlyProcess, Action seen) =>
        new() { _probing = true, OnlyProcess = onlyProcess, Seen = seen };

    /// <summary>
    /// Self-test: checks on this machine that the hooks install, that a key press is seen and that a
    /// click is seen at the right screen point. It presses F24 (a key no program uses) and clicks once
    /// at (<paramref name="x"/>, <paramref name="y"/>), which the caller makes sure is on a window of
    /// its own where a click does nothing. The mouse pointer is put back afterwards.
    /// </summary>
    public static (bool Installed, bool KeySeen, RecordedStep? Click) Probe(int x, int y)
    {
        var recorder = new InputRecorder { _probing = true };
        Native.GetCursorPos(out var pointer);
        recorder.Start();
        try
        {
            Thread.Sleep(150);
            InputSender.TapVirtual(0x87);
            Thread.Sleep(100);
            InputSender.MoveTo(x, y);
            Thread.Sleep(150);
            InputSender.MouseClick();
            Thread.Sleep(300);
        }
        finally
        {
            Native.SetCursorPos(pointer.X, pointer.Y);
        }
        var seen = recorder.Stop();
        return (recorder.Installed, seen.Unrepeatable is not null,
            seen.Steps.FirstOrDefault(step => step.Kind == RecordedKind.Click));
    }

    public void Start()
    {
        if (_thread is not null) return;
        _lastAt = Environment.TickCount64;
        _thread = new Thread(Run) { IsBackground = true, Name = "input-recorder" };
        _thread.Start();
        _ready.Wait(3000);
    }

    public Recording Stop()
    {
        if (_thread is { } thread)
        {
            if (_threadId != 0) Native.PostThreadMessageW(_threadId, Native.WmQuit, IntPtr.Zero, IntPtr.Zero);
            thread.Join(3000);
            _thread = null;
        }
        lock (_steps)
        {
            var reason = _unrepeatable ?? (Installed ? null : "o Windows não permitiu observar o teclado e o mouse");
            return new Recording(_steps.ToArray(), reason);
        }
    }

    /// <summary>The hooks only deliver events to a thread that pumps messages: this one does nothing else.</summary>
    private void Run()
    {
        _threadId = Native.GetCurrentThreadId();
        _mouseProc = MouseHook;
        _keyProc = KeyHook;
        var module = Native.GetModuleHandleW(null);
        var mouse = Native.SetWindowsHookExW(Native.WhMouseLl, _mouseProc, module, 0);
        var keyboard = Native.SetWindowsHookExW(Native.WhKeyboardLl, _keyProc, module, 0);
        Installed = mouse != IntPtr.Zero && keyboard != IntPtr.Zero;
        _ready.Set();
        try
        {
            while (Native.GetMessageW(out _, IntPtr.Zero, 0, 0) > 0)
            {
            }
        }
        finally
        {
            if (mouse != IntPtr.Zero) Native.UnhookWindowsHookEx(mouse);
            if (keyboard != IntPtr.Zero) Native.UnhookWindowsHookEx(keyboard);
        }
    }

    // The callbacks run before the event reaches its window, so they must return quickly and never throw.

    private IntPtr MouseHook(int code, IntPtr wParam, IntPtr lParam)
    {
        try
        {
            var message = (int)wParam;
            if (code >= 0 && message is Native.WmLeftButtonDown or Native.WmRightButtonDown)
            {
                var data = Marshal.PtrToStructure<Native.MSLLHOOKSTRUCT>(lParam);
                if (_probing || (data.flags & Native.MouseHookInjected) == 0)
                    OnMouseDown(message == Native.WmRightButtonDown, data.pt);
            }
        }
        catch (Exception)
        {
            // A lost event only means a screen is not learned.
        }
        return Native.CallNextHookEx(IntPtr.Zero, code, wParam, lParam);
    }

    private IntPtr KeyHook(int code, IntPtr wParam, IntPtr lParam)
    {
        try
        {
            var message = (int)wParam;
            if (code >= 0)
            {
                var data = Marshal.PtrToStructure<Native.KBDLLHOOKSTRUCT>(lParam);
                if (_probing || (data.flags & Native.KeyHookInjected) == 0)
                {
                    var key = (int)data.vkCode;
                    if (message is Native.WmKeyUp or Native.WmSysKeyUp) _held.Remove(key);
                    else if (message is Native.WmKeyDown or Native.WmSysKeyDown && _held.Add(key)) OnKeyDown(key);
                }
            }
        }
        catch (Exception)
        {
        }
        return Native.CallNextHookEx(IntPtr.Zero, code, wParam, lParam);
    }

    private void OnMouseDown(bool right, Native.POINT point)
    {
        if (!Counts(Native.WindowFromPoint(point))) return;
        lock (_steps)
        {
            var now = Environment.TickCount64;
            if (!right && _steps.Count > 0 && _steps[^1] is { Kind: RecordedKind.Click } last &&
                now - _lastAt <= _doubleClickMs && Math.Abs(last.X - point.X) <= 4 && Math.Abs(last.Y - point.Y) <= 4)
            {
                _steps[^1] = last with { Kind = RecordedKind.DoubleClick };
                _lastAt = now;
            }
            else
            {
                Add(new RecordedStep(right ? RecordedKind.RightClick : RecordedKind.Click, point.X, point.Y), now);
            }
        }
        Seen?.Invoke();
    }

    private void OnKeyDown(int key)
    {
        if (IsModifier(key) || key == VkPause) return;
        if (!Counts(Native.GetForegroundWindow())) return; // e.g. typed into this program's own search box

        bool control = Down(VkControl), alt = Down(VkAlt), shift = Down(VkShift);
        if (Down(VkLeftWin) || Down(VkRightWin)) return; // Windows shortcuts are not about the screen
        if (control && alt && key is 'P' or 'Q') return;  // the pause and stop shortcuts
        if (alt && key is 0x09 or 0x1B) return;           // Alt+Tab / Alt+Esc only switch windows
        if (key is 0x2C or 0x14 or 0x90 or 0x91) return;  // Print Screen and the lock keys change nothing

        lock (_steps)
        {
            var now = Environment.TickCount64;
            if (!control && IsAnswerKey(key, alt))
                Add(new RecordedStep(RecordedKind.Key, Key: key, Alt: alt, Shift: shift), now);
            else
                _unrepeatable ??= "foi digitado texto ou usado um atalho que o robô não repete sozinho";
        }
        Seen?.Invoke();
    }

    /// <summary>The keys that answer a dialog: they are safe to press again on the same dialog.</summary>
    private static bool IsAnswerKey(int key, bool alt)
    {
        if (alt) return key is >= 'A' and <= 'Z' or >= '0' and <= '9'; // a button's underlined letter
        return key is 0x0D or 0x1B or 0x09 or 0x20 or >= 0x25 and <= 0x28; // Enter, Esc, Tab, Space, arrows
    }

    private void Add(RecordedStep step, long now)
    {
        if (_steps.Count >= MaxSteps)
        {
            _unrepeatable ??= $"foram mais de {MaxSteps} ações";
            return;
        }
        _steps.Add(step with { DelayMs = (int)Math.Min(now - _lastAt, 60_000) });
        _lastAt = now;
    }

    /// <summary>Whether input going to this window is recorded: not this program's own windows, and
    /// only the watched program when there is one.</summary>
    private bool Counts(IntPtr window)
    {
        if (window == IntPtr.Zero) return OnlyProcess == 0;
        Native.GetWindowThreadProcessId(window, out var process);
        if (process == _ownProcess && !_probing) return false;
        return OnlyProcess == 0 || process == OnlyProcess;
    }

    private static bool Down(int key) => (Native.GetAsyncKeyState(key) & 0x8000) != 0;

    private static bool IsModifier(int key) =>
        key is VkShift or VkControl or VkAlt or VkLeftWin or VkRightWin or >= 0xA0 and <= 0xA5;
}

/// <summary>How the bot repeats a recorded action.</summary>
public interface IRecoveryInput
{
    void Click(int x, int y, RecordedKind kind);
    void Key(int key, bool alt, bool shift);
    void Wait(int ms);
}

/// <summary>Repeats recorded actions with real mouse and keyboard events.</summary>
public sealed class SendInputRecovery : IRecoveryInput
{
    public void Click(int x, int y, RecordedKind kind)
    {
        InputSender.MoveTo(x, y);
        Thread.Sleep(120);
        InputSender.MouseClick(right: kind == RecordedKind.RightClick);
        if (kind == RecordedKind.DoubleClick) InputSender.MouseClick();
    }

    public void Key(int key, bool alt, bool shift)
    {
        if (alt) InputSender.KeyDown(Bsoft.Key.Alt);
        if (shift) InputSender.KeyDown(Bsoft.Key.Shift);
        try
        {
            InputSender.TapVirtual(key);
        }
        finally
        {
            if (shift) InputSender.KeyUp(Bsoft.Key.Shift);
            if (alt) InputSender.KeyUp(Bsoft.Key.Alt);
        }
    }

    public void Wait(int ms) => Thread.Sleep(ms);
}
